// Turns the photos listed in photos.json into web-sized images for the site.
// Writes docs/img/* and docs/gallery.js. Location/camera metadata is dropped (sharp strips it by default).
// usage: node tools/build-images.cjs
const sharp = require('C:/Users/Newen Guest/wedding-photos/tools/node_modules/sharp');
const fs = require('fs'), path = require('path');

const root = path.join(__dirname, '..');
const cfg = JSON.parse(fs.readFileSync(path.join(__dirname, 'photos.json'), 'utf8'));
const out = path.join(root, 'docs', 'img');
fs.mkdirSync(out, { recursive: true });
const src = p => path.isAbsolute(p) ? p : path.join(cfg.base, p);

async function web(file, name, long, quality = 80) {
  const info = await sharp(src(file)).rotate().resize(long, long, { fit: 'inside', withoutEnlargement: true })
    .webp({ quality, smartSubsample: true }).toFile(path.join(out, name));
  return { w: info.width, h: info.height };
}

(async () => {
  // old generated files out of the way, so removed photos disappear
  for (const f of fs.readdirSync(out)) if (/^(g|r)-\d+.*\.webp$/.test(f)) fs.unlinkSync(path.join(out, f));

  // hero: 3:4 portrait
  const h = cfg.hero;
  await sharp(src(h.file)).rotate()
    .resize(900, 1200, { fit: 'cover', position: h.position || 'attention' })
    .webp({ quality: 82 }).toFile(path.join(out, 'hero.webp'));

  const gallery = { reel: [], grid: [] };
  for (const [key, prefix] of [['reel', 'r'], ['grid', 'g']]) {
    let i = 0;
    for (const file of cfg[key]) {
      i++;
      const n = String(i).padStart(2, '0');
      const t = await web(file, `${prefix}-${n}.webp`, 760, 78);
      await web(file, `${prefix}-${n}-full.webp`, 1600, 82);
      gallery[key].push({ src: `img/${prefix}-${n}.webp`, full: `img/${prefix}-${n}-full.webp`, ...t });
    }
  }
  fs.writeFileSync(path.join(root, 'docs', 'gallery.js'),
    `// generated by tools/build-images.cjs — edit tools/photos.json instead\nwindow.GALLERY = ${JSON.stringify(gallery, null, 1)};\n`);

  // link-preview card 1200x630: photo on the left, names on the right
  const og = cfg.og || cfg.hero;
  const photo = await sharp(src(og.file)).rotate().resize(520, 630, { fit: 'cover', position: og.position || 'attention' }).toBuffer();
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630">
    <defs>
      <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#7a1222"/><stop offset="1" stop-color="#3a0610"/></linearGradient>
      <linearGradient id="gold" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#c9a24a"/><stop offset=".5" stop-color="#fff3c4"/><stop offset="1" stop-color="#c9a24a"/></linearGradient>
      <pattern id="dots" width="24" height="24" patternUnits="userSpaceOnUse"><circle cx="12" cy="12" r="1.6" fill="#f8e6a8" fill-opacity=".14"/></pattern>
    </defs>
    <rect width="1200" height="630" fill="url(#bg)"/>
    <rect x="520" width="680" height="630" fill="url(#dots)"/>
    <rect x="548" y="28" width="624" height="574" fill="none" stroke="#c9a24a" stroke-width="2"/>
    <rect x="558" y="38" width="604" height="554" fill="none" stroke="#c9a24a" stroke-opacity=".5" stroke-width="1"/>
    <g text-anchor="middle" font-family="Georgia, 'Times New Roman', serif" fill="#f8e6a8">
      <text x="860" y="140" font-size="26" letter-spacing="8">YOU ARE INVITED</text>
      <text x="860" y="260" font-size="96" font-style="italic" fill="url(#gold)">Vedanshi</text>
      <text x="860" y="320" font-size="34" letter-spacing="10">WEDS</text>
      <text x="860" y="420" font-size="96" font-style="italic" fill="url(#gold)">Bhavya</text>
      <line x1="700" y1="472" x2="1020" y2="472" stroke="#c9a24a" stroke-width="1.5"/>
      <text x="860" y="525" font-size="34" letter-spacing="6">28 · 02 · 2027</text>
    </g>
  </svg>`;
  await sharp(Buffer.from(svg)).composite([{ input: photo, left: 0, top: 0 }])
    .jpeg({ quality: 84, mozjpeg: true }).toFile(path.join(out, 'og.jpg'));

  const total = fs.readdirSync(out).reduce((s, f) => s + fs.statSync(path.join(out, f)).size, 0);
  console.log(`hero + ${gallery.reel.length} reel + ${gallery.grid.length} grid photos, img/ = ${(total / 1e6).toFixed(1)} MB`);
})();
